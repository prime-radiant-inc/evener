// newRealSummarizerManager builds a Manager with a real cheap-model client.
// It skips the test if no provider API keys are present in the environment.
func newRealSummarizerManager(t *testing.T) *Manager {
	t.Helper()

	// Gate on any known provider key. The providers are registered via the
	// blank imports at the top of the file; llm.NewFromEnv will find them.
	knownKeys := []string{
		"OPENAI_API_KEY",
		"ANTHROPIC_API_KEY",
		"GEMINI_API_KEY",
		"GOOGLE_API_KEY",
	}
	hasKey := false
	for _, k := range knownKeys {
		if os.Getenv(k) != "" {
			hasKey = true
			break
		}
	}
	if !hasKey {
		t.Skip("no LLM API key set (OPENAI_API_KEY, ANTHROPIC_API_KEY, GEMINI_API_KEY, GOOGLE_API_KEY); skipping obedience eval")
	}

	client, err := llm.NewFromEnv()
	if err != nil {
		t.Skipf("llm.NewFromEnv: %v", err)
	}

	// Build a profile using the first available provider so the Manager can
	// resolve a cheap model.  The contextmgr testProfile helper is in this
	// package and handles that cleanly.
	var prof *provider.Profile
	switch {
	case os.Getenv("OPENAI_API_KEY") != "":
		prof = provider.NewOpenAIProfile("gpt-5.4-mini")
	case os.Getenv("ANTHROPIC_API_KEY") != "":
		prof = testProfile("anthropic", "claude-haiku-4-5-20251001", 0)
	case os.Getenv("GEMINI_API_KEY") != "" || os.Getenv("GOOGLE_API_KEY") != "":
		prof = testProfile("google", "gemini-2.5-flash-lite", 0)
	default:
		t.Skip("no profile could be built for available provider")
	}

	return NewManager(prof, client)
}

// turnsFromText converts a raw text string into a slice of schema.Turns large
// enough to exceed PreserveRecentTurns=2 so that summarizeWithLLMSteered has
// content to compact. The text is placed as the first UserInput turn; two
// short filler turns follow so that safeCutoff has room to set a non-negative
// cutoff at len-2.
func turnsFromText(t *testing.T, text string) []schema.Turn {
	t.Helper()
	return []schema.Turn{
		schema.NewTurn(schema.TurnUserInput, llm.User(text)),
		schema.NewTurn(schema.TurnAssistant, llm.Assistant("Acknowledged. Continuing work.")),
		schema.NewTurn(schema.TurnUserInput, llm.User("Proceed.")),
		schema.NewTurn(schema.TurnAssistant, llm.Assistant("Continuing.")),
	}
}

// summaryText extracts the text content from the first TurnSummary in the
// result slice returned by summarizeWithLLMSteered.
func summaryText(turns []schema.Turn) string {
	for _, t := range turns {
		if t.Kind == schema.TurnSummary {
			return t.Message.Text()
		}
	}
	return ""
}

// block formats a named block of content for embedding in a history string.
func block(name, content string) string {
	return "=== BEGIN " + name + " ===\n" + content + "=== END " + name + " ===\n"
}

// fact formats a must-keep fact for embedding in a history string.
func fact(text string) string {
	return "IMPORTANT FACT: " + text + "\n"
}

// repeat repeats s n times.
func repeat(s string, n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteString(s)
	}
	return b.String()
}
