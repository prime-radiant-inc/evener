// TestSummarizeObedience is an eval (//go:build eval) that measures whether
// the configured cheap summarization model honors drop/keep directives in
// compaction_instructions. Requires >=90% of cases honored and ZERO
// must-keep drops. Failure means the instruction path must NOT ship.
func TestSummarizeObedience(t *testing.T) {
	cm := newRealSummarizerManager(t)
	cases := obedienceCases()

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	honored, keepViolations := 0, 0
	for _, c := range cases {
		hist := turnsFromText(t, c.history)
		out, err := cm.summarizeWithLLMSteered(ctx, hist, 2, c.instruction)
		if err != nil {
			t.Fatalf("case %q: summarizeWithLLMSteered: %v", c.name, err)
		}
		summary := summaryText(out)

		if c.mustKeep != "" && !strings.Contains(summary, c.mustKeep) {
			keepViolations++
			t.Errorf("case %q DROPPED a must-keep %q\n  instruction: %s\n  summary (first 500): %.500s",
				c.name, c.mustKeep, c.instruction, summary)
			continue
		}
		if c.mustDrop != "" && strings.Contains(summary, c.mustDrop) {
			t.Logf("case %q failed to drop %q", c.name, c.mustDrop)
			continue
		}
		honored++
	}

	rate := float64(honored) / float64(len(cases))
	t.Logf("obedience rate: %.2f (%d/%d), must-keep violations: %d", rate, honored, len(cases), keepViolations)

	if keepViolations > 0 {
		t.Fatalf("instruction path must NOT ship: %d must-keep drops", keepViolations)
	}
	if rate < 0.90 {
		t.Fatalf("obedience rate %.2f < 0.90 — instruction path fails the gate", rate)
	}
}

