// Package gatesurface is the single authored definition of which tests the
// deterministic non-fuzz gate runs, shared by the gate itself and by the
// coverage ratchet that must measure the same surface. The shell consumers
// source scripts/lib/gate-surface-lib.sh, which ShellLib generates from this
// package (make generate); that file is an artifact, not a second home.
//
// This lives in one file because the alternative is two copies that drift. A
// ratchet measuring a different surface than the gate proves is worse than no
// ratchet: the number moves for reasons no one can attribute, and the floor
// ends up blessed against a surface no gate reproduces.
package gatesurface

import (
	"fmt"
	"strings"
)

// FuzzTestSkip is the regex matching fuzz-designated Test* functions excluded
// from the regular deterministic gate. Native Fuzz* targets are already
// excluded by -run; these names cover rapid/sequence fuzz tests and
// structured-generator reachability proofs that remain under make fuzz.
var FuzzTestSkip = `(SeqFuzz|SchemaFuzz|Structured.*Reach|LifecycleAdapter|ToolArgsAdapter|SeqAdapter|TurnPagingEquivalenceSanity|WireTypeRegistryCoverage|LineWindowExtractorsSanity|WriteListRoundTrip|LaunchConfigThreeStateRoundTrip|DifferentialSanity|StreamVsNonStreamSanity|FuzzBuildEnforces)`

// TestRun is the regex for which tests the gate runs. The gate runs ordinary
// Test/Example functions only; without this filter `go test` also executes
// every native Fuzz target's committed seed corpus, which is make fuzz's job,
// not the default gate's.
var TestRun = `^(Test|Example)`

// HubIntegrationRun is the regex for the hub's runner-bound integration tests:
// the members of testing-budget.json's deploy-host integration, retirement,
// live-stack E2E classes. The default gate skips them so the timing ratchet
// measures the stable suite; the hub-integration gate runs exactly this set,
// outside the ratchet.
var HubIntegrationRun = `^(TestHostDeployFilesystemSafety|TestHubRPCThreadListServesRemoteHostWhoseAttachOutlastsLocalBudget|TestValidateDeployBinaryAcceptsAGenuineEvenerArtifact|TestDaemonRetirementProcessAdmittedWorkResetsInterval|TestDaemonRetirementProcessDirectPositiveExits|TestDaemonRetirementProcessDirectZeroStaysResident|TestDaemonRetirementProcessHelperExitsWithItsFixture|TestDaemonRetirementProcessHubZeroStaysResident|TestDaemonRetirementProcessReadsDoNotResetInterval|TestDaemonRetirementProcessRestartedHubRediscoversOrResumes|TestE2E_StopIsOfferedWheneverTheWireSaysActive|TestE2E_SendPromptToARetiredSession|TestE2E_SendPromptAfterDaemonDiedMidTurn|TestE2E_ControlInvariantDuringPreTurnWorkOnTheFirstTurn|TestE2E_ControlInvariantDuringPreTurnWorkAtATurnBoundary)$`

//go:generate go run ../../../cmd/evener-dev/bin dev gate-surface -root ../../..

// ShardSkip returns the -skip regex a shard runner gets: the gate's own skip,
// plus a caller's *_SHARD_SKIP as an alternative when one is set, so a test the
// caller asked to skip stays skipped under the gate too. Either side may be
// empty; an empty side is left out rather than joined, since "|(x)" has an
// empty alternative that matches, and so skips, every test.
func ShardSkip(gate, user string) string {
	if gate != "" && user != "" {
		return gate + "|(" + user + ")"
	}
	return gate + user
}

// ShellLib returns scripts/lib/gate-surface-lib.sh: the shell consumers'
// sourceable form of this package. The generated file is committed because the
// gate and the ratchets run without building evener-dev first; make
// generate rewrites it, and TestShellLibMatchesGeneration fails on drift.
func ShellLib() string {
	var b strings.Builder
	b.WriteString(`#!/usr/bin/env bash
# gate-surface-lib.sh — generated by internal/devtool/gatesurface from
# gatesurface.go (make generate); DO NOT EDIT.
#
# The single definition of WHICH tests the deterministic non-fuzz gate runs,
# shared by the gate itself (run-module-tests.sh) and by the ratchets that must
# measure the same surface (evener dev coverage-floor, test-timing-budget.sh).
#
# Sourced, never executed. Deliberately pure declaration: it sets variables
# and defines pure lookup functions and does nothing else (no file writes, no
# process launches), so it is safe for the dev-tooling wave's leak check.
#
# This lives in one generated file because the alternative is two copies that
# drift. A ratchet measuring a different surface than the gate proves is worse
# than no ratchet: the number moves for reasons no one can attribute, and the
# floor ends up blessed against a surface no gate reproduces.

# Fuzz-designated Test* functions are not part of the regular gate. Native Fuzz*
# targets are already excluded by -run; these names cover rapid/sequence fuzz
# tests and structured-generator reachability proofs that remain under make fuzz.
`)
	fmt.Fprintf(&b, "GATE_FUZZ_TEST_SKIP='%s'\n\n", FuzzTestSkip)
	b.WriteString(`# The gate runs ordinary Test/Example functions only. Without this filter
# ` + "`go test`" + ` also executes every native Fuzz target's committed seed corpus,
# which is make fuzz's job, not the default gate's.
`)
	fmt.Fprintf(&b, "GATE_TEST_RUN='%s'\n\n", TestRun)
	b.WriteString(`# The hub's runner-bound integration tests: the members of testing-budget.json's
# deploy-host integration, retirement, and live-stack E2E classes. The default
# gate skips them so the timing ratchet measures the stable suite; the
# hub-integration gate runs exactly this set, outside the ratchet, and the
# gatesurface tests pin this list to those classes.
`)
	fmt.Fprintf(&b, "GATE_HUB_INTEGRATION_RUN='%s'\n\n", HubIntegrationRun)
	b.WriteString(`# gate_shard_skip GATE USER — the -skip regex a shard runner gets: the gate's
# own skip, plus a caller's *_SHARD_SKIP as an alternative when one is set, so
# a test the caller asked to skip stays skipped under the gate too.
# Either side may be empty; an empty side is left out rather than joined, since
# "|(x)" has an empty alternative that matches, and so skips, every test.
gate_shard_skip() {
	if [ -n "$1" ] && [ -n "$2" ]; then
		printf '%s|(%s)' "$1" "$2"
	else
		printf '%s' "$1$2"
	fi
}
`)
	return b.String()
}
