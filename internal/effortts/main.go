// Command effortts writes the TypeScript mirror of llm/effort, so the shared
// client cannot restate the reasoning-effort ladder (#5553). The generated
// file is committed and its freshness is checked by `make lint-generated`.
package main

//go:generate go run . -out ../../appwire-client/typescript/reasoningEffort.gen.ts

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"primeradiant.com/evener/llm/effort"
)

func main() {
	out := flag.String("out", "", "generated TypeScript file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "effortts: -out is required")
		os.Exit(2)
	}
	if err := os.WriteFile(*out, []byte(render()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "effortts: %v\n", err)
		os.Exit(1)
	}
}

// render returns the generated module. FALLBACK_EFFORT_LEVELS is the prefix
// of the ladder a picker offers when a reasoning model enumerates no levels.
func render() string {
	tiers := effort.Tiers()
	fallback := tiers
	if len(fallback) > 4 {
		fallback = fallback[:4]
	}
	var b strings.Builder
	b.WriteString("// Code generated by primeradiant.com/evener/internal/effortts; DO NOT EDIT.\n")
	b.WriteString("//\n// The one definition is llm/effort; regenerate with `make generate`.\n\n")
	b.WriteString("// EFFORT_TIERS is the daemon's reasoning-effort ladder, least to most.\n")
	fmt.Fprintf(&b, "export const EFFORT_TIERS: string[] = %s;\n\n", tsArray(tiers))
	b.WriteString("// FALLBACK_EFFORT_LEVELS is the four-tier ladder a picker offers when a\n")
	b.WriteString("// reasoning model does not enumerate its own levels.\n")
	fmt.Fprintf(&b, "export const FALLBACK_EFFORT_LEVELS: string[] = %s;\n", tsArray(fallback))
	return b.String()
}

func tsArray(levels []string) string {
	quoted := make([]string, len(levels))
	for i, level := range levels {
		quoted[i] = fmt.Sprintf("%q", level)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}
