package main

import (
	"fmt"
	"strings"
)

const maxConsumers = 3

func consumerCell(consumers []string) string {
	if len(consumers) == 0 {
		return "none"
	}
	shown := consumers
	extra := 0
	if len(shown) > maxConsumers {
		extra = len(shown) - maxConsumers
		shown = shown[:maxConsumers]
	}
	cell := "`" + strings.Join(shown, "`, `") + "`"
	if extra > 0 {
		cell += fmt.Sprintf(" and %d more", extra)
	}
	return cell
}

func docCell(doc string) string {
	if doc == "" {
		return "none"
	}
	return "[" + doc + "](../" + doc + ")"
}

func render(env []envRow, direct []directRow, hub []hubRow, removed []string) string {
	var b strings.Builder
	b.WriteString(`<!-- Code generated by internal/knobtable (make generate); DO NOT EDIT. -->

# Configuration Knobs

Every environment variable and ` + "`hub.toml`" + ` key the code reads, with the doc
that explains it and the code that consumes it. The tables are generated from
the ` + "`envvars`" + ` registry and the decoder in ` + "`cmd/evener-hub/config.go`" + `, so
a knob that nothing reads shows up as "none" in the Consumer column, and
` + "`internal/knobtable`" + `'s repo test fails on it. Delete such a knob, and list a
removed ` + "`hub.toml`" + ` key in ` + "`removedKnobs`" + ` so a file that still sets it starts
with a warning.

An environment variable has no default of its own: unset means the consuming
code's built-in behavior, which the doc row describes. A variable the
models.dev catalog or the provider overlay names is read by ` + "`llm/registry`" + `
without a Go identifier, so that is its consumer; a Go reference counts
unless it only sets or clears the variable, and references from test-support
packages do not count.

## Environment variables in the registry

| Variable | Visibility | Doc row | Consumer |
|---|---|---|---|
`)
	for _, r := range env {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.Name, r.Visibility, docCell(r.DocRow), consumerCell(r.Consumers))
	}
	b.WriteString(`
## Environment variables read outside the registry

Dev tooling and test rigs declare these themselves.

| Variable | Doc row | Consumer |
|---|---|---|
`)
	for _, r := range direct {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.Name, docCell(r.DocRow), consumerCell(r.Consumers))
	}
	b.WriteString(`
## hub.toml keys

Scalar keys only; the ` + "`[[hosts]]`" + ` and ` + "`[[providers]]`" + ` tables and the
machine-managed host records are described in [the hub guide](../evener-hub.md).

| Key | Default | Doc row | Consumer |
|---|---|---|---|
`)
	for _, r := range hub {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.Key, defaultCell(r.Default), docCell(r.DocRow), consumerCell(r.Consumers))
	}
	b.WriteString("\n## Removed hub.toml keys\n\nA `hub.toml` that still sets one of these starts normally and logs a warning naming the key.\n\n")
	for _, k := range removed {
		fmt.Fprintf(&b, "- `%s`\n", k)
	}
	return b.String()
}

func defaultCell(d string) string {
	switch d {
	case "unset", "computed at startup":
		return d
	case `""`:
		return "unset"
	}
	return "`" + d + "`"
}
